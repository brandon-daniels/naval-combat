"""Generate runtime closed hull pieces from the authored fracture source."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parts = json.loads((root / 'Assets/models/reference_ship/reference_ship_breakaway.json').read_text())['parts']
def vec(v):
    return 'new Vector3( ' + ', '.join(f'{x:.6f}f' for x in v) + ' )'
lines = ['// Generated by Tools/build_ship_plank_catalog.py.', 'namespace NavalCombat;',
         'internal static class ShipPlankCatalog', '{', '\tinternal static readonly ShipPartDefinition[] Parts = Create();', '\tprivate static ShipPartDefinition[] Create()', '\t{', f'\t\tvar parts = new ShipPartDefinition[{len(parts)}];']
for index, p in enumerate(parts):
    center = [sum(v[i] for v in p['vertices']) / len(p['vertices']) for i in range(3)]
    vertices = [[v[i]-center[i] for i in range(3)] for v in p['vertices']]
    points = 'new Vector3[] { ' + ', '.join(vec(v) for v in vertices) + ' }'
    faces = 'new int[][] { ' + ', '.join('new int[] { '+', '.join(map(str,f))+' }' for f in p['faces']) + ' }'
    lines.append(f'\t\tparts[{index}] = Part{index}();')
    lines.append(f'\t\t//ENTRY{index} new ShipPartDefinition( "{p["id"]}", {vec(center)}, {vec(center)}, 0.08f, "{p["material"]}", 0, -1, -1, false, {points}, {faces} ),')
entries = [line for line in lines if '//ENTRY' in line]
lines = [line for line in lines if '//ENTRY' not in line]
lines += ['\t\treturn parts;', '\t}']
for index, entry in enumerate(entries):
    expression = entry.split(f'//ENTRY{index} ', 1)[1].rstrip(',')
    lines.append(f'\tprivate static ShipPartDefinition Part{index}() => {expression};')
lines += ['}']
(root / 'Code/Ships/ShipPlankCatalog.cs').write_text('\n'.join(lines)+'\n')
